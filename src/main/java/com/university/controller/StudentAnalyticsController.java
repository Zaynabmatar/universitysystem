    /** A circular progress ring: navy/indigo arc over a light track, percent + credits centered. */
    private VBox buildProgressRing(Analytics a) {
        double size = 190;
        Canvas canvas = new Canvas(size, size);
        GraphicsContext gc = canvas.getGraphicsContext2D();
        double stroke = 16;
        double pad = stroke / 2 + 2;

        gc.setLineCap(javafx.scene.shape.StrokeLineCap.ROUND);
        gc.setLineWidth(stroke);

        gc.setStroke(Color.web("#e6ebf1"));
        gc.strokeArc(pad, pad, size - 2 * pad, size - 2 * pad, 90, -360, javafx.scene.shape.ArcType.OPEN);

        double fraction = a.progressFraction();

        DoubleProperty animatedFraction = new SimpleDoubleProperty(0.0);

        animatedFraction.addListener((obs, oldValue, newValue) -> {
            gc.clearRect(0, 0, size, size);

            gc.setLineCap(javafx.scene.shape.StrokeLineCap.ROUND);
            gc.setLineWidth(stroke);

            gc.setStroke(Color.web("#e6ebf1"));
            gc.strokeArc(pad, pad, size - 2 * pad, size - 2 * pad,
                    90, -360, javafx.scene.shape.ArcType.OPEN);

            gc.setStroke(Color.web("#4f46e5"));
            gc.strokeArc(pad, pad, size - 2 * pad, size - 2 * pad,
                    90, -360 * newValue.doubleValue(),
                    javafx.scene.shape.ArcType.OPEN);
        });

        new Timeline(
                new KeyFrame(Duration.ZERO,
                        new KeyValue(animatedFraction, 0.0)),
                new KeyFrame(Duration.millis(2500),
                        new KeyValue(animatedFraction, fraction))
        ).play();

        Label percent = new Label(a.progressPercent.setScale(0, java.math.RoundingMode.HALF_UP) + "%");
        percent.setStyle("-fx-font-size: 30px; -fx-font-weight: bold; -fx-text-fill: #1f395c;");
        Label caption = new Label("Graduation Progress");
        caption.getStyleClass().add("muted-text");
        Label credits = new Label(a.completedCredits + " / " + a.requiredCredits + " crds");
        credits.getStyleClass().add("muted-text");

        VBox centerText = new VBox(2, percent, caption, credits);
        centerText.setAlignment(Pos.CENTER);

        StackPane stack = new StackPane(canvas, centerText);
        stack.setPrefSize(size, size);

        VBox box = new VBox(6, stack);
        box.setAlignment(Pos.CENTER);
        return box;
    }

    /** A semicircular 0.0-4.0 GPA gauge: four colour bands (weak to strong) plus a needle. */
    private VBox buildGpaGauge(Analytics a) {
        double width = 240;
        double height = 150;
        Canvas canvas = new Canvas(width, height);
        GraphicsContext gc = canvas.getGraphicsContext2D();

        double stroke = 18;
        double pad = stroke / 2 + 4;
        double diameter = width - 2 * pad;
        double cx = width / 2.0;
        double cy = height - pad - 4;

        gc.setLineCap(javafx.scene.shape.StrokeLineCap.BUTT);
        gc.setLineWidth(stroke);

        String[] bandColors = {"#c0392b", "#e0812f", "#d9b021", "#2f7d4f"};
        for (int i = 0; i < 4; i++) {
            gc.setStroke(Color.web(bandColors[i]));
            gc.strokeArc(pad, pad, diameter, diameter, 180 - i * 45, -45, javafx.scene.shape.ArcType.OPEN);
        }

        double gpa = a.cumulativeGpa.doubleValue();
        double gpaClamped = Math.max(0.0, Math.min(4.0, gpa));
        double needleLength = diameter / 2.0 - 6;

        DoubleProperty animatedGpa = new SimpleDoubleProperty(0.0);
        animatedGpa.addListener((obs, oldVal, newVal) -> {
            gc.clearRect(0, 0, width, height);

            gc.setLineCap(javafx.scene.shape.StrokeLineCap.BUTT);
            gc.setLineWidth(stroke);
            for (int i = 0; i < 4; i++) {
                gc.setStroke(Color.web(bandColors[i]));
                gc.strokeArc(pad, pad, diameter, diameter,
                        180 - i * 45, -45, javafx.scene.shape.ArcType.OPEN);
            }

            double angle = 180.0 - (newVal.doubleValue() / 4.0) * 180.0;
            double rad = Math.toRadians(angle);
            double nx = cx + needleLength * Math.cos(rad);
            double ny = cy - needleLength * Math.sin(rad);

            gc.setLineWidth(3);
            gc.setStroke(Color.web("#1f395c"));
            gc.strokeLine(cx, cy, nx, ny);
            gc.setFill(Color.web("#1f395c"));
            gc.fillOval(cx - 5, cy - 5, 10, 10);
        });

        new Timeline(
                new KeyFrame(Duration.ZERO, new KeyValue(animatedGpa, 0.0)),
                new KeyFrame(Duration.millis(3000), new KeyValue(animatedGpa, gpaClamped))
        ).play();

        Label value = new Label(GradeCalculator.formatGpa(a.cumulativeGpa));
        value.setStyle("-fx-font-size: 24px; -fx-font-weight: bold; -fx-text-fill: #1f395c;");
        Label caption = new Label("GPA  (0.0 - 4.0)");
        caption.getStyleClass().add("muted-text");
        Label standing = new Label(a.standingLabel);
        standing.getStyleClass().add("badge");
        standing.getStyleClass().add(gpaBadgeClass(gpaClamped));

        VBox labels = new VBox(2, value, caption);
        labels.setAlignment(Pos.CENTER);

        StackPane canvasStack = new StackPane(canvas);
        canvasStack.setPrefSize(width, height);

        VBox box = new VBox(6, canvasStack, labels, standing);
        box.setAlignment(Pos.CENTER);
        return box;
    }

    private String gpaBadgeClass(double gpa) {
        if (gpa >= 3.5) return "badge-ok";
        if (gpa >= 2.0) return "badge-neutral";
        return "badge-danger";
    }

