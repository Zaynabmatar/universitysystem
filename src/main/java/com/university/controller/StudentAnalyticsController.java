    private void renderProjection(Analytics a) {
        projectionChart.getData().clear();

        boolean hasData = !a.projection.isEmpty();
        if (!hasData) {
            ChartUtil.showOrExplain(projectionChart, projectionEmpty, false);
            return;
        }

        List<String> labels = new ArrayList<>();
        Set<String> seen = new LinkedHashSet<>();
        for (ProjectionPoint p : a.projection) {
            if (seen.add(p.label)) {
                labels.add(p.label);
            }
        }
        ((CategoryAxis) projectionChart.getXAxis()).setCategories(FXCollections.observableArrayList(labels));

        XYChart.Series<String, Number> perSemester = new XYChart.Series<>();
        perSemester.setName("Per-Semester Completed Credits");
        XYChart.Series<String, Number> cumulative = new XYChart.Series<>();
        cumulative.setName("Cumulative Completed Credits");
        XYChart.Series<String, Number> trend = new XYChart.Series<>();
        trend.setName("Projected Trend (Plan of Study)");
        XYChart.Series<String, Number> target = new XYChart.Series<>();
        target.setName("Graduation Target (" + a.requiredCredits + " Credits)");

        for (ProjectionPoint p : a.projection) {
            if (p.perSemesterCredits != null) {
                perSemester.getData().add(new XYChart.Data<>(p.label, p.perSemesterCredits));
            }
            if (p.cumulativeCredits != null) {
                cumulative.getData().add(new XYChart.Data<>(p.label, p.cumulativeCredits));
            }
            if (p.projectedCumulativeCredits != null) {
                trend.getData().add(new XYChart.Data<>(p.label, p.projectedCumulativeCredits));
            }
            target.getData().add(new XYChart.Data<>(p.label, p.graduationTarget));
        }

        projectionChart.getData().addAll(perSemester, cumulative, trend, target);
        ChartUtil.showOrExplain(projectionChart, projectionEmpty, true);
    }

