/* ============================================================================
   0005 — fix the bulk-import password hashes

   WHY
     Every account's password is supposed to be BCrypt of the mandatory
     default <user_id>@iuL (PasswordHasher.hashDefaultPassword,
     UserDAO.finalizePassword). One batch never got that: 270 STUDENT accounts
     (user_id 423-692, username bf00001-bf00270) were loaded by a bulk import
     outside the application and all 270 share one single identical bcrypt
     hash - a common password set at import time, unrelated to any per-account
     id, and not recorded anywhere. Nobody can derive what it was, so none of
     these 270 accounts can sign in with any expected password. Every other
     account in dbo.users has its own distinct hash and is unaffected.

     This migration rewrites exactly those 270 rows to BCrypt of their own
     <user_id>@iuL, matching every other account created by the application.
     The hashes below were generated with the project's own BCrypt settings
     (org.mindrot.jbcrypt, cost 12, one random salt per row - PasswordHasher's
     exact call) offline against a read-only export of the affected user_id
     list; nothing here is a placeholder or a re-derivation from a weaker
     source, and the plaintext password exists nowhere in this file or in the
     database, only the hash.

   SAFE TO RE-RUN
     Guarded on the shared hash still being in place: only a row whose
     password_hash still equals the one common bulk-import value is touched.
     Once rewritten, a row no longer matches that guard, so a second run (or
     a partial one picked up again after an interruption) updates nothing.
============================================================================ */

